// Window Object
// It is the parent object of all objects in JavaScript (browser environment).
// It is available in the heap area.
// Some built-in objects and functions inside the window object are:
// console
// alert()
// prompt()
// document (DOM)
// All properties and methods of the window object can be accessed directly without using the window. prefix.
// Example:
// JavaScript
// alert("Hello");
// window.alert("Hello");
// Both are valid.

